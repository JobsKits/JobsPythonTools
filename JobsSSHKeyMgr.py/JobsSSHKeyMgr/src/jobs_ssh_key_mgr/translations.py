def resolve_language(locale_name: str | None) -> str:
    """把系统区域标识映射到支持语言，未知区域使用英语。"""
    value = (locale_name or "").strip().replace("-", "_").lower()
    value = value.split(".", 1)[0].split("@", 1)[0]
    if value.startswith("zh"):
        parts = value.split("_")
        return "zh_TW" if "hant" in parts or any(part in {"tw", "hk", "mo"} for part in parts) else "zh_CN"
    if value.startswith(("bo", "tibetan")):
        return "bo"
    prefix = value.split("_", 1)[0].split(".", 1)[0].split("@", 1)[0]
    return prefix if prefix in TR else "en"


